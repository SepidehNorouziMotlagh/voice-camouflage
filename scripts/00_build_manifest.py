"""
Build Utterance Role Manifest

This script creates the utterance role splits for each target speaker:
- Selection set: utterances used to compute speaker embeddings for background selection
- Enrollment set: utterances used by the ASV attacker for enrollment
- Evaluation set: utterances used to create clean references and mixtures

The splits are saved to a JSON manifest file for use in subsequent pipeline steps.
"""
import json
import random
from pathlib import Path

# ------------------------- Configuration -------------------------
BASE_DIR = Path(__file__).parent.parent
DATA_DIR = BASE_DIR / "data"
CONFIG_DIR = BASE_DIR / "config"
MANIFEST_FILE = CONFIG_DIR / "utterance_roles.json"

# Paths to the audio file lists (generated by collect_paths.py)
TARGET_AUDIO_FILE = DATA_DIR / "target_audio_paths.json"
BACKGROUND_AUDIO_FILE = DATA_DIR / "background_audio_paths.json"

# Load speaker audio file lists
with open(TARGET_AUDIO_FILE) as f:
    target_audio = json.load(f)

with open(BACKGROUND_AUDIO_FILE) as f:
    background_audio = json.load(f)

# Seed for reproducibility
RANDOM_SEED = 42
random.seed(RANDOM_SEED)

# Number of utterances per role
N_SELECTION = 2
N_ENROLLMENT = 1
N_EVALUATION = 1

# Minimum utterances required per speaker to participate
MIN_UTTERANCES = N_SELECTION + N_ENROLLMENT + N_EVALUATION
# ----------------------------------------------------------------

def split_utterances(utterance_list, n_selection, n_enrollment, n_evaluation):
    """
    Split utterances into three fixed groups: selection, enrollment, evaluation.

    Args:
        utterance_list: List of file paths for a speaker
        n_selection: Number of utterances for selection set
        n_enrollment: Number of utterances for enrollment set
        n_evaluation: Number of utterances for evaluation set

    Returns:
        dict: Contains three lists: "selection", "enrollment", "evaluation"
    """
    # Shuffle to avoid any ordering bias
    shuffled = utterance_list.copy()
    random.shuffle(shuffled)

    selection = shuffled[:n_selection]
    enrollment = shuffled[n_selection:n_selection + n_enrollment]
    evaluation = shuffled[n_selection + n_enrollment:n_selection + n_enrollment + n_evaluation]

    return {
        "selection": selection,
        "enrollment": enrollment,
        "evaluation": evaluation,
        "all": utterance_list
    }

def main():
    print("=" * 60)
    print("UTTERANCE ROLE MANIFEST BUILDER")
    print("=" * 60)

    # Filter speakers with enough utterances
    valid_targets = {}
    for spk, files in target_audio.items():
        if len(files) >= MIN_UTTERANCES:
            valid_targets[spk] = files
        else:
            print(f"⚠️ Target {spk} has only {len(files)} utterances (need {MIN_UTTERANCES}) — excluding")

    valid_backgrounds = {}
    for spk, files in background_audio.items():
        if len(files) >= 1:  # Backgrounds only need one utterance for selection
            valid_backgrounds[spk] = files
        else:
            print(f"⚠️ Background {spk} has only {len(files)} utterances — excluding")

    print(f"\n✅ Valid targets: {len(valid_targets)}")
    print(f"✅ Valid backgrounds: {len(valid_backgrounds)}")

    # Build utterance role splits for each target
    target_roles = {}
    for spk, files in valid_targets.items():
        target_roles[spk] = split_utterances(files, N_SELECTION, N_ENROLLMENT, N_EVALUATION)

    # Build and save the manifest
    manifest = {
        "targets": target_roles,
        "backgrounds": valid_backgrounds,
        "metadata": {
            "n_selection": N_SELECTION,
            "n_enrollment": N_ENROLLMENT,
            "n_evaluation": N_EVALUATION,
            "min_utterances": MIN_UTTERANCES,
            "random_seed": RANDOM_SEED,
            "total_targets": len(valid_targets),
            "total_backgrounds": len(valid_backgrounds),
        }
    }

    CONFIG_DIR.mkdir(parents=True, exist_ok=True)

    with open(MANIFEST_FILE, "w") as f:
        json.dump(manifest, f, indent=2)

    print(f"\n✅ Manifest saved to {MANIFEST_FILE}")

    # Print summary
    print("\n" + "=" * 60)
    print("MANIFEST SUMMARY")
    print("=" * 60)
    print(f"Target speakers: {len(valid_targets)}")
    print(f"Background speakers: {len(valid_backgrounds)}")
    print(f"Selection utterances per target: {N_SELECTION}")
    print(f"Enrollment utterances per target: {N_ENROLLMENT}")
    print(f"Evaluation utterances per target: {N_EVALUATION}")

if __name__ == "__main__":
    main()